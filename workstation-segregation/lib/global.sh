#!/bin/bash
# Global (per-user) configuration owned by the kit. Requires lib/common.sh.

claude_hook_cmd() { printf '/bin/bash %s/hooks/direnv-session-env.sh' "$KIT_ROOT"; }

setup_shell() {
  block_insert "$HOME/.bashrc" shell <<EOF
export WORKSTATION_SEGREGATION_ROOT="$KIT_ROOT"
export WORKSTATION_SEGREGATION_BIN="$BIN_DIR"
export WORKSTATION_SEGREGATION_CONFIG="$CONFIG_FILE"
[ -r "$KIT_ROOT/shell/bashrc.sh" ] && . "$KIT_ROOT/shell/bashrc.sh"
EOF

  # Login shells: macOS Terminal reads ~/.bash_profile. On Linux, ~/.profile
  # already sources ~/.bashrc, and creating ~/.bash_profile would shadow it.
  local bp="$HOME/.bash_profile"
  if [ -f "$bp" ] || [ "$KIT_OS" = darwin ]; then
    if [ ! -f "$bp" ] && [ -f "$HOME/.profile" ] && [ "$DRY_RUN" != 1 ]; then
      printf '[ -r "$HOME/.profile" ] && . "$HOME/.profile"\n' > "$bp"
    fi
    block_insert "$bp" shell <<EOF
export WORKSTATION_SEGREGATION_ROOT="$KIT_ROOT"
export WORKSTATION_SEGREGATION_BIN="$BIN_DIR"
[ -r "$KIT_ROOT/shell/bash_profile.sh" ] && . "$KIT_ROOT/shell/bash_profile.sh"
EOF
  fi
  local f
  for f in "$HOME/.bashrc" "$HOME/.bash_profile"; do
    if grep -qE '^# >>> workstation (bash_profile )?managed >>>' "$f" 2>/dev/null; then
      warn "$f still has the OLD ../workstation managed block: remove it to avoid duplicate direnv hook/starship/PROMPT_COMMAND, but FIRST copy its PATH (/opt/homebrew/bin), EDITOR and nvm lines elsewhere in the file (see README, Migrating)"
    fi
  done
  if [ -f "$HOME/Documents/.workstation-projects" ]; then
    warn "old auto-allow list ~/Documents/.workstation-projects exists; the kit no longer reads it (safe to delete once migrated)"
  fi
  case "${SHELL:-}" in
    */bash) ;;
    *) warn "login shell is '${SHELL:-unknown}', not bash. Switch with: chsh -s /bin/bash (kit integration is bash-only)" ;;
  esac
}

setup_git() {
  local before k v changed=0
  if [ "$DRY_RUN" = 1 ]; then
    log "DRY-RUN: apply git defaults from templates/git-global.conf, drop global gh credential helpers, add [include] last"
    return 0
  fi
  before="$(mktemp "${TMPDIR:-/tmp}/wsk-gitconfig.XXXXXX")"
  [ -f "$HOME/.gitconfig" ] && cp -p "$HOME/.gitconfig" "$before" || : > "$before"

  while IFS='=' read -r k v; do
    case "$k" in ''|'#'*) continue ;; esac
    case "$k" in
      # Required for segregation: always enforced.
      user.useConfigOnly|credential.helper) git config --global "$k" "$v" ;;
      # Preferences: only set when the user has no value.
      *) git config --global --get "$k" >/dev/null 2>&1 || git config --global "$k" "$v" ;;
    esac
  done < "$KIT_ROOT/templates/git-global.conf"

  # Gap fix: `gh auth setup-git` writes global github helpers that come after
  # (and override) the per-client helper. Remove them; the per-client config
  # supplies gh as the credential helper inside each client directory.
  for k in credential.https://github.com.helper credential.https://gist.github.com.helper; do
    if git config --global --get-all "$k" >/dev/null 2>&1; then
      git config --global --unset-all "$k"
      log "removed global git setting $k (per-client helper replaces it)"
    fi
  done

  mkdir -p "$KIT_CONFIG_DIR"
  [ -f "$KIT_CONFIG_DIR/gitconfig-clients" ] || printf '# Generated by workstation-segregation.\n' > "$KIT_CONFIG_DIR/gitconfig-clients"

  # Must be the LAST thing in ~/.gitconfig so client config overrides globals.
  block_insert "$HOME/.gitconfig" include <<EOF
[include]
	path = $KIT_CONFIG_DIR/gitconfig-clients
EOF

  cmp -s "$before" "$HOME/.gitconfig" || changed=1
  if [ "$changed" = 1 ]; then
    mv "$before" "$HOME/.gitconfig.bak.$(date +%Y%m%d%H%M%S)"
    log "previous ~/.gitconfig saved as ~/.gitconfig.bak.*"
  else
    rm -f "$before"
  fi

  if grep -q '^\[includeIf "gitdir' "$HOME/.gitconfig" 2>/dev/null; then
    warn "~/.gitconfig has hand-written includeIf blocks; the kit now generates them. Remove yours once verified (duplicates are harmless)."
  fi
}

# Add (idempotently) the SessionStart hook to ~/.claude/settings.json.
setup_claude_hook() {
  local f="$HOME/.claude/settings.json" cmd tmp jqbin
  cmd="$(claude_hook_cmd)"
  jqbin="$(PATH="$BIN_DIR:$PATH" command -v jq 2>/dev/null || true)"
  if [ -z "$jqbin" ]; then
    warn "jq not available; skipping Claude hook (re-run deploy after tools install)"
    return 0
  fi
  if [ "$DRY_RUN" = 1 ]; then
    log "DRY-RUN: register SessionStart hook in $f"
    return 0
  fi
  mkdir -p "$HOME/.claude"
  [ -f "$f" ] || printf '{}\n' > "$f"
  if grep -q 'workstation/config/claude/direnv-session-env.sh' "$f" 2>/dev/null; then
    warn "$f has the OLD SessionStart hook (workstation/config/claude/...): remove it, otherwise the hook runs twice"
  fi
  tmp="$(mktemp "${TMPDIR:-/tmp}/wsk-claude.XXXXXX")"
  if ! "$jqbin" --arg cmd "$cmd" '
      .hooks.SessionStart = (
        ((.hooks.SessionStart // [])
          | map(select(([.hooks[]?.command] | index($cmd)) | not)))
        + [{"hooks":[{"type":"command","command":$cmd}]}])' "$f" > "$tmp"; then
    rm -f "$tmp"
    warn "could not parse $f; Claude hook not registered"
    return 0
  fi
  if cmp -s "$tmp" "$f"; then
    log "unchanged: $f (hook)"
  else
    backup_file "$f"
    cat "$tmp" > "$f"
    log "updated: $f (SessionStart hook)"
  fi
  rm -f "$tmp"
}

remove_claude_hook() {
  local f="$HOME/.claude/settings.json" cmd tmp jqbin
  [ -f "$f" ] || return 0
  cmd="$(claude_hook_cmd)"
  jqbin="$(PATH="$BIN_DIR:$PATH" command -v jq 2>/dev/null || true)"
  [ -n "$jqbin" ] || { warn "jq not available; remove the kit SessionStart hook from $f manually"; return 0; }
  grep -qF "$cmd" "$f" || return 0
  if [ "$DRY_RUN" = 1 ]; then
    log "DRY-RUN: remove SessionStart hook from $f"
    return 0
  fi
  tmp="$(mktemp "${TMPDIR:-/tmp}/wsk-claude.XXXXXX")"
  "$jqbin" --arg cmd "$cmd" '
      .hooks.SessionStart |= map(select(([.hooks[]?.command] | index($cmd)) | not))' "$f" > "$tmp" \
    && { backup_file "$f"; cat "$tmp" > "$f"; log "removed Claude hook from $f"; }
  rm -f "$tmp"
}

global_install() {
  setup_shell
  setup_git
  setup_claude_hook
}

global_uninstall() {
  block_remove "$HOME/.bashrc" shell
  block_remove "$HOME/.bash_profile" shell
  block_remove "$HOME/.gitconfig" include
  remove_claude_hook
  run rm -f "$KIT_CONFIG_DIR/gitconfig-clients"
  log "note: global git defaults and removed gh credential helpers are not restored (see ~/.gitconfig.bak.*)"
}
