# workstation-segregation common aliases (portable between macOS and Linux).
if ls --color=auto >/dev/null 2>&1; then alias ls="ls --color=auto"; else alias ls="ls -G"; fi
alias ll="ls -alF"
alias la="ls -A"
alias l="ls -CF"
alias ..="cd .."
alias ...="cd ../.."
alias ....="cd ../../.."
alias cp="cp -i"
alias mv="mv -i"
alias rm="rm -i"
alias g="git"
alias gs="git status --short"
alias gst="git status"
alias ga="git add"
alias gc="git commit"
alias gco="git checkout"
alias gb="git branch"
alias gl="git log --oneline --decorate --graph"
alias gp="git pull --ff-only"
alias k="kubectl"
alias kgctx="kubectl config get-contexts"
alias hlt="helm lint"
alias htmpl="helm template"
